#!/usr/bin/env python3
"""Step 45: writes backup/MsPrefCatalog.java = every ms_* preference key of the settings screens with its
type (b = switch, s = list/text, set = multi-select) and, for lists with fixed entries, the allowed values.
The Jieshuo settings restore uses it so a value of the wrong type or outside the list is never written.
Run again after a settings screen changes:  python3 devtools/step45/gen_catalog.py"""
import glob, os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "talkback/src/main/res")
OUT = os.path.join(ROOT, "talkback/src/main/java/com/google/android/accessibility/talkback/backup/MsPrefCatalog.java")
values = ""
for f in glob.glob(os.path.join(RES, "values", "*.xml")):
    values += open(f, encoding="utf8").read()
def array(name):
    m = re.search(r'<(?:string-array|array|integer-array)\s+name="%s"[^>]*>(.*?)</(?:string-array|array|integer-array)>' % re.escape(name), values, re.S)
    return [re.sub(r"\s+", " ", x).strip() for x in re.findall(r"<item[^>]*>(.*?)</item>", m.group(1), re.S)] if m else None
cat = {}
for f in sorted(glob.glob(os.path.join(RES, "xml*", "*.xml"))):
    t = open(f, encoding="utf8").read()
    for m in re.finditer(r"<([\w\.]+)\s([^>]*?android:key=\"(ms_[A-Za-z0-9_]+)\"[^>]*?)/?>", t, re.S):
        tag = m.group(1).split(".")[-1]; attrs = m.group(2); key = m.group(3)
        if "Switch" in tag or "CheckBox" in tag: typ = "b"
        elif "MultiSelect" in tag: typ = "set"
        elif "List" in tag or "EditText" in tag: typ = "s"
        else: continue
        allowed = ""
        ev = re.search(r'android:entryValues="@array/([^"]+)"', attrs)
        if ev and typ in ("s", "set"):
            a = array(ev.group(1))
            if a: allowed = "|".join(a)
        old = cat.get(key)
        if old and old[0] != typ:
            continue  # same key twice with another type: keep the first
        cat[key] = (typ, allowed)
rows = ",\n".join('      {"%s", "%s", "%s"}' % (k, v[0], v[1].replace("\\", "\\\\").replace('"', '\\"')) for k, v in sorted(cat.items()))
open(OUT, "w", encoding="utf8").write('''package com.google.android.accessibility.talkback.backup;

import java.util.HashMap;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;

/** GENERATED by devtools/step45/gen_catalog.py - do not edit by hand. Pure Java (no Android). */
final class MsPrefCatalog {
  private MsPrefCatalog() {}

  /** {key, type (b / s / set), allowed values separated by | or empty when the list is not fixed}. */
  private static final String[][] ROWS = {
%s
  };

  private static final Map<String, String[]> BY_KEY = new HashMap<>();

  static {
    for (String[] r : ROWS) {
      BY_KEY.put(r[0], r);
    }
  }

  static boolean has(String key) {
    return BY_KEY.containsKey(key);
  }

  /** "b", "s" or "set"; null when the key is not a setting of this app. */
  static String type(String key) {
    String[] r = BY_KEY.get(key);
    return r == null ? null : r[1];
  }

  /** The allowed values of a fixed list, or null when anything is accepted. */
  static Set<String> allowed(String key) {
    String[] r = BY_KEY.get(key);
    if (r == null || r[2].isEmpty()) {
      return null;
    }
    Set<String> s = new HashSet<>();
    for (String v : r[2].split("\\\\|")) {
      s.add(v);
    }
    return s;
  }
}
''' % rows)
print("keys:", len(cat), "with fixed lists:", sum(1 for v in cat.values() if v[1]))
