package com.google.android.accessibility.talkback.preference.base;

import android.content.Context;
import android.content.Intent;
import android.content.pm.PackageManager;
import android.content.pm.ResolveInfo;
import android.os.Bundle;
import androidx.preference.MultiSelectListPreference;
import androidx.preference.Preference;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Base of the Operation settings and Advanced settings screens that copy Jieshuo's structure
 * (generated by devtools/step19_gen/gen_settings.py). Only job: fills the "choose applications"
 * lists with the installed apps. Not compiled yet.
 */
public abstract class MsJxBaseFragment extends TalkbackBaseFragment {
  private static final String[] APP_LISTS = {"ms_jx_game_mode", "ms_jx_app_no_key_shortcut"};

  protected MsJxBaseFragment(int xmlResId) {
    super(xmlResId);
  }

  @Override
  public void onCreatePreferences(Bundle savedInstanceState, String rootKey) {
    super.onCreatePreferences(savedInstanceState, rootKey);
    Context context = getContext();
    if (context == null) {
      return;
    }
    for (String key : APP_LISTS) {
      Preference p = findPreference(key);
      if (p instanceof MultiSelectListPreference) {
        fillApps(context, (MultiSelectListPreference) p);
      }
    }
  }

  private static void fillApps(Context context, MultiSelectListPreference pref) {
    PackageManager pm = context.getPackageManager();
    Intent main = new Intent(Intent.ACTION_MAIN).addCategory(Intent.CATEGORY_LAUNCHER);
    List<ResolveInfo> found = pm.queryIntentActivities(main, 0);
    Map<String, String> byPackage = new LinkedHashMap<>();
    for (ResolveInfo r : found) {
      byPackage.put(r.activityInfo.packageName, r.loadLabel(pm).toString());
    }
    List<Map.Entry<String, String>> rows = new ArrayList<>(byPackage.entrySet());
    Collections.sort(rows, (a, b) -> a.getValue().compareToIgnoreCase(b.getValue()));
    CharSequence[] names = new CharSequence[rows.size()];
    CharSequence[] ids = new CharSequence[rows.size()];
    for (int i = 0; i < rows.size(); i++) {
      names[i] = rows.get(i).getValue();
      ids[i] = rows.get(i).getKey();
    }
    pref.setEntries(names);
    pref.setEntryValues(ids);
  }
}
